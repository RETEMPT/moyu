import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const config = JSON.parse(fs.readFileSync(path.join(root, 'release/app-market.json'), 'utf8'));
const privacy = JSON.parse(fs.readFileSync(path.join(root, 'release/privacy-sections.json'), 'utf8'));
const sections = [...privacy.sections, { title: '发布信息与隐私咨询', body: config.publisher && config.supportEmail && config.privacyUrl
  ? `发布者：${config.publisher}。隐私咨询与个人信息权利请求：${config.supportEmail}。在线隐私政策：${config.privacyUrl}。我们将在 ${config.privacyResponseWorkingDays} 个工作日内回复。说明更新日期：${privacy.updatedAt}。`
  : `开发版本的发布主体、隐私咨询联系方式与在线政策尚未填写，暂不能提交应用市场。项目反馈：github.com/RETEMPT/moyu/issues；请勿公开私人资料和密钥。说明更新日期：${privacy.updatedAt}。` }];
const source = `// Generated by tools/generate-market-materials.mjs; edit release/privacy-sections.json and release/app-market.json.\n` +
  `export interface PrivacySection { title: string; body: string; }\nexport const PRIVACY_SECTIONS: PrivacySection[] = ${JSON.stringify(sections, null, 2)};\n`;
const info = `// Generated public publication metadata; never add signing secrets here.\n` +
  `export const PUBLISHER: string = ${JSON.stringify(config.publisher)};\nexport const SUPPORT_EMAIL: string = ${JSON.stringify(config.supportEmail)};\nexport const PRIVACY_URL: string = ${JSON.stringify(config.privacyUrl)};\n`;
const escape = text => text.replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const html = `<!doctype html>\n<html lang="zh-CN"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">\n` +
  `<title>${escape(config.appName)}隐私与数据说明</title>\n<style>body{max-width:760px;margin:auto;padding:24px;font:17px/1.8 system-ui,sans-serif;color:#172033;background:#fff}h1{font-size:28px}h2{font-size:20px;margin-top:28px}p{white-space:pre-wrap;overflow-wrap:anywhere}@media(prefers-color-scheme:dark){body{background:#121a26;color:#e8eef8}}</style>\n` +
  `<h1>${escape(config.appName)}隐私与数据说明</h1>\n${sections.map(s => `<section><h2>${escape(s.title)}</h2><p>${escape(s.body)}</p></section>`).join('\n')}\n</html>\n`;
const markdown = `# ${config.appName}隐私与数据说明\n\n更新：${privacy.updatedAt}。本文与应用内、在线页面由同一份资料生成；编辑 release 下的配置后重新生成。\n\n` + sections.map(s => `## ${s.title}\n\n${s.body}\n`).join('\n');
const outputs = new Map([
  ['entry/src/main/ets/common/constants/PrivacyNotice.ets', source],
  ['entry/src/main/ets/common/constants/PublicationInfo.ets', info],
  ['release/site/privacy.html', html],
  ['docs/PRIVACY.md', markdown]
]);
if (process.argv.includes('--check')) {
  const changed = [...outputs].filter(([file, content]) => !fs.existsSync(path.join(root, file)) || fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n') !== content);
  if (changed.length) { console.error('发布资料与应用内说明不一致，请重新生成：' + changed.map(([f]) => f).join(', ')); process.exitCode = 1; }
  else console.log('应用内与在线隐私说明一致。');
} else {
  for (const [file, content] of outputs) { fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true }); fs.writeFileSync(path.join(root, file), content); }
  console.log('已生成应用内说明、公开发布信息与可托管的隐私页面。');
}
